const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
// The scope boundary excludes Appica primitives AND their descendants. Keep
// existing specialized canvas/history layouts without leaking into components.
const css = ['desktop.css', 'workspace.css'].map(name => fs.readFileSync(path.join(root, name), 'utf8')).join('\n');
fs.writeFileSync(path.join(root, 'frontend/legacy-layout.generated.css'),
    `/* Generated by scripts/build-ui-layout.js */\n@scope (:root) to ([data-slot]) {\n${css}\n}\n`);
